// Q6 — Positive / Negative / Zero

// User se ek number lo:

// 0 → Positive

// < 0 → Negative

// == 0 → Zero

// 👉 Use: if–else if–els

let number = 0 ;
if (number > 0 ){
    console.log("Positive")
} else if (number < 0 ){
    console.log (" Negative")
}else{
    console.log("Zero")
}