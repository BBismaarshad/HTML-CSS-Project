// Q8 — Password Strength Checker

// Password variable do:

// Length < 5 → Weak

// Length 5–8 → Medium

// Length > 8 → Strong

// 👉 Use: if–else if–else + string.length


let passwordCheckar = "mypassword123";

if(passwordCheckar.length < 5 ){
    console.log("Weak")
}else if (passwordCheckar.length <= 8 ){
    console.log("Medium")

}else{
    console.log(" Strong")
}



